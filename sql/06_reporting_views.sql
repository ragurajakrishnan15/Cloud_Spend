-- REPORTING views: the only objects the dashboard / AI analyst should read.
-- Ratios are fractions (0.05 = 5%) and are NULL when the denominator is zero (DIV0NULL).
USE SCHEMA CLOUDSPEND_AI.REPORTING;

-- Grain: day x department x service x environment x region.
CREATE OR REPLACE VIEW VW_DAILY_CLOUD_SPEND AS
SELECT d.FULL_DATE AS USAGE_DATE, d.YEAR_MONTH, d.IS_WEEKEND,
       dep.DEPARTMENT_NAME, s.SERVICE_NAME, e.ENVIRONMENT_NAME, g.REGION_NAME,
       SUM(f.TOTAL_COST) AS TOTAL_COST, SUM(f.USAGE_UNITS) AS USAGE_UNITS, COUNT(*) AS RECORD_COUNT
FROM CLOUDSPEND_AI.ANALYTICS.FACT_CLOUD_COST f
JOIN CLOUDSPEND_AI.ANALYTICS.DIM_DATE d ON d.DATE_KEY = f.DATE_KEY
JOIN CLOUDSPEND_AI.ANALYTICS.DIM_DEPARTMENT dep ON dep.DEPARTMENT_KEY = f.DEPARTMENT_KEY
JOIN CLOUDSPEND_AI.ANALYTICS.DIM_SERVICE s ON s.SERVICE_KEY = f.SERVICE_KEY
JOIN CLOUDSPEND_AI.ANALYTICS.DIM_ENVIRONMENT e ON e.ENVIRONMENT_KEY = f.ENVIRONMENT_KEY
JOIN CLOUDSPEND_AI.ANALYTICS.DIM_REGION g ON g.REGION_KEY = f.REGION_KEY
GROUP BY 1, 2, 3, 4, 5, 6, 7;

-- Grain: month x department x service x environment x region.
CREATE OR REPLACE VIEW VW_MONTHLY_CLOUD_SPEND AS
SELECT DATE_TRUNC('month', USAGE_DATE) AS MONTH_START, YEAR_MONTH,
       DEPARTMENT_NAME, SERVICE_NAME, ENVIRONMENT_NAME, REGION_NAME,
       SUM(TOTAL_COST) AS TOTAL_COST, SUM(USAGE_UNITS) AS USAGE_UNITS,
       COUNT(DISTINCT USAGE_DATE) AS DAYS_WITH_DATA
FROM VW_DAILY_CLOUD_SPEND
GROUP BY 1, 2, 3, 4, 5, 6;

-- Grain: month x department x service. Budgets exist ONLY at this grain, so environment/region filters
-- must not be applied to budget comparisons. A department-service-month present on one side only is kept.
CREATE OR REPLACE VIEW VW_BUDGET_VARIANCE AS
WITH actual AS (
  SELECT d.MONTH_START_DATE AS MONTH_START, f.DEPARTMENT_KEY, f.SERVICE_KEY, SUM(f.TOTAL_COST) AS ACTUAL_COST
  FROM CLOUDSPEND_AI.ANALYTICS.FACT_CLOUD_COST f
  JOIN CLOUDSPEND_AI.ANALYTICS.DIM_DATE d ON d.DATE_KEY = f.DATE_KEY
  GROUP BY 1, 2, 3
), joined AS (
  SELECT COALESCE(a.MONTH_START, b.BUDGET_MONTH) AS MONTH_START,
         COALESCE(a.DEPARTMENT_KEY, b.DEPARTMENT_KEY) AS DEPARTMENT_KEY,
         COALESCE(a.SERVICE_KEY, b.SERVICE_KEY) AS SERVICE_KEY,
         COALESCE(a.ACTUAL_COST, 0) AS ACTUAL_COST, COALESCE(b.BUDGET_AMOUNT, 0) AS BUDGET_AMOUNT
  FROM actual a
  FULL OUTER JOIN CLOUDSPEND_AI.ANALYTICS.FACT_BUDGET b
    ON a.MONTH_START = b.BUDGET_MONTH AND a.DEPARTMENT_KEY = b.DEPARTMENT_KEY AND a.SERVICE_KEY = b.SERVICE_KEY
)
SELECT j.MONTH_START, TO_CHAR(j.MONTH_START, 'YYYY-MM') AS YEAR_MONTH,
       dep.DEPARTMENT_NAME, s.SERVICE_NAME, j.ACTUAL_COST, j.BUDGET_AMOUNT,
       j.ACTUAL_COST - j.BUDGET_AMOUNT AS VARIANCE_AMOUNT,                    -- positive = over budget
       DIV0NULL(j.ACTUAL_COST - j.BUDGET_AMOUNT, j.BUDGET_AMOUNT) AS VARIANCE_PCT,
       (j.ACTUAL_COST > j.BUDGET_AMOUNT) AS IS_OVER_BUDGET
FROM joined j
JOIN CLOUDSPEND_AI.ANALYTICS.DIM_DEPARTMENT dep ON dep.DEPARTMENT_KEY = j.DEPARTMENT_KEY
JOIN CLOUDSPEND_AI.ANALYTICS.DIM_SERVICE s ON s.SERVICE_KEY = j.SERVICE_KEY;

-- Grain: month x department. MoM change is NULL for the first month; IS_PARTIAL_MONTH flags incomplete months.
CREATE OR REPLACE VIEW VW_DEPARTMENT_COST_TRENDS AS
WITH m AS (
  SELECT MONTH_START, DEPARTMENT_NAME, SUM(TOTAL_COST) AS TOTAL_COST, MAX(DAYS_WITH_DATA) AS DAYS_WITH_DATA
  FROM VW_MONTHLY_CLOUD_SPEND GROUP BY 1, 2
)
SELECT MONTH_START, DEPARTMENT_NAME, TOTAL_COST,
       LAG(TOTAL_COST) OVER (PARTITION BY DEPARTMENT_NAME ORDER BY MONTH_START) AS PREV_MONTH_COST,
       TOTAL_COST - PREV_MONTH_COST AS MOM_CHANGE_AMOUNT,
       DIV0NULL(TOTAL_COST - PREV_MONTH_COST, PREV_MONTH_COST) AS MOM_CHANGE_PCT,
       DAYS_WITH_DATA, (DAYS_WITH_DATA < DAY(LAST_DAY(MONTH_START))) AS IS_PARTIAL_MONTH
FROM m;

-- Grain: month x service.
CREATE OR REPLACE VIEW VW_SERVICE_COST_TRENDS AS
WITH m AS (
  SELECT MONTH_START, SERVICE_NAME, SUM(TOTAL_COST) AS TOTAL_COST, MAX(DAYS_WITH_DATA) AS DAYS_WITH_DATA
  FROM VW_MONTHLY_CLOUD_SPEND GROUP BY 1, 2
)
SELECT MONTH_START, SERVICE_NAME, TOTAL_COST,
       LAG(TOTAL_COST) OVER (PARTITION BY SERVICE_NAME ORDER BY MONTH_START) AS PREV_MONTH_COST,
       TOTAL_COST - PREV_MONTH_COST AS MOM_CHANGE_AMOUNT,
       DIV0NULL(TOTAL_COST - PREV_MONTH_COST, PREV_MONTH_COST) AS MOM_CHANGE_PCT,
       DAYS_WITH_DATA, (DAYS_WITH_DATA < DAY(LAST_DAY(MONTH_START))) AS IS_PARTIAL_MONTH
FROM m;

