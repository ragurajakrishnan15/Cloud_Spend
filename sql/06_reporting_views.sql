LEFT JOIN CLOUDSPEND_AI.ANALYTICS.DIM_SERVICE s ON s.SERVICE_KEY = r.SERVICE_KEY;

-- Grain: calendar quarter. Actual vs budget and QoQ change; IS_PARTIAL_QUARTER flags incomplete periods.
CREATE OR REPLACE VIEW VW_QBR_METRICS AS
WITH act AS (
  SELECT d.QUARTER_START_DATE AS QUARTER_START, d.YEAR_QUARTER, SUM(f.TOTAL_COST) AS ACTUAL_COST,
         COUNT(DISTINCT d.FULL_DATE) AS DAYS_WITH_DATA
  FROM CLOUDSPEND_AI.ANALYTICS.FACT_CLOUD_COST f
  JOIN CLOUDSPEND_AI.ANALYTICS.DIM_DATE d ON d.DATE_KEY = f.DATE_KEY
  GROUP BY 1, 2
), bud AS (
  SELECT DATE_TRUNC('quarter', BUDGET_MONTH) AS QUARTER_START, SUM(BUDGET_AMOUNT) AS BUDGET_AMOUNT
  FROM CLOUDSPEND_AI.ANALYTICS.FACT_BUDGET GROUP BY 1
)
SELECT a.QUARTER_START, a.YEAR_QUARTER, a.ACTUAL_COST, COALESCE(b.BUDGET_AMOUNT, 0) AS BUDGET_AMOUNT,
       a.ACTUAL_COST - COALESCE(b.BUDGET_AMOUNT, 0) AS VARIANCE_AMOUNT,
       DIV0NULL(a.ACTUAL_COST - COALESCE(b.BUDGET_AMOUNT, 0), b.BUDGET_AMOUNT) AS VARIANCE_PCT,
       LAG(a.ACTUAL_COST) OVER (ORDER BY a.QUARTER_START) AS PREV_QUARTER_COST,
       DIV0NULL(a.ACTUAL_COST - PREV_QUARTER_COST, PREV_QUARTER_COST) AS QOQ_CHANGE_PCT,
       a.DAYS_WITH_DATA,
       (a.DAYS_WITH_DATA < DATEDIFF(day, a.QUARTER_START, DATEADD(month, 3, a.QUARTER_START))) AS IS_PARTIAL_QUARTER
FROM act a LEFT JOIN bud b ON b.QUARTER_START = a.QUARTER_START;

-- Latest successful ingestion OF THE FILE the analytics layer was built from (not merely the latest load of any file),
-- for the dashboard's "last refreshed" indicator.
CREATE OR REPLACE VIEW VW_DATA_REFRESH AS
SELECT FILE_NAME, ROWS_LOADED, LOADED_COST_SUM, FINISHED_AT AS LAST_SUCCESSFUL_LOAD
FROM CLOUDSPEND_AI.RAW.INGESTION_RUNS
WHERE STATUS = 'SUCCESS'
  AND FILE_NAME = (SELECT MAX(SOURCE_FILE) FROM CLOUDSPEND_AI.ANALYTICS.FACT_CLOUD_COST)
QUALIFY ROW_NUMBER() OVER (ORDER BY FINISHED_AT DESC) = 1;

CREATE OR REPLACE VIEW VW_MODEL_EVALUATION AS
SELECT RUN_ID, MODEL_FAMILY, MODEL_NAME, MODEL_VERSION, SCOPE, METRIC_NAME, METRIC_VALUE, PARAMETERS, CREATED_AT
FROM CLOUDSPEND_AI.ANALYTICS.MODEL_EVALUATION;
