CREATE OR REPLACE VIEW VW_OPTIMIZATION_RECOMMENDATIONS AS
SELECT r.RECOMMENDATION_ID, r.RULE_NAME, r.RULE_VERSION, dep.DEPARTMENT_NAME, s.SERVICE_NAME,
       r.PERIOD_START, r.PERIOD_END, r.EVIDENCE, r.SUGGESTED_ACTION,
       COALESCE(TO_VARCHAR(r.ESTIMATED_SAVINGS), 'Requires investigation') AS ESTIMATED_SAVINGS_DISPLAY,
       r.ESTIMATED_SAVINGS, r.SAVINGS_FORMULA, r.CONFIDENCE, r.REVIEW_STATUS, r.CREATED_AT
FROM CLOUDSPEND_AI.ANALYTICS.FACT_OPTIMIZATION_RECOMMENDATION r
