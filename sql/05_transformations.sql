-- Rebuilds dimensions and facts from ONE raw source file. Placeholders are substituted by the Python runner:
--   {{SOURCE_FILE}} billing file name, {{BUDGET_FILE}} budgets file name.
-- INSERT OVERWRITE makes each table swap atomic and the whole script safe to rerun.
-- No raw records are excluded (RAW is validated at load time), so ANALYTICS cost == RAW cost for the file.
USE SCHEMA CLOUDSPEND_AI.ANALYTICS;

INSERT OVERWRITE INTO DIM_DEPARTMENT
SELECT DENSE_RANK() OVER (ORDER BY DEPARTMENT), DEPARTMENT FROM
  (SELECT DEPARTMENT FROM CLOUDSPEND_AI.RAW.CLOUD_BILLING_RAW WHERE SOURCE_FILE = '{{SOURCE_FILE}}'
   UNION SELECT DEPARTMENT FROM CLOUDSPEND_AI.RAW.BUDGETS_RAW WHERE SOURCE_FILE = '{{BUDGET_FILE}}');

INSERT OVERWRITE INTO DIM_SERVICE
SELECT DENSE_RANK() OVER (ORDER BY SERVICE_NAME), SERVICE_NAME FROM
  (SELECT SERVICE_NAME FROM CLOUDSPEND_AI.RAW.CLOUD_BILLING_RAW WHERE SOURCE_FILE = '{{SOURCE_FILE}}'
   UNION SELECT SERVICE_NAME FROM CLOUDSPEND_AI.RAW.BUDGETS_RAW WHERE SOURCE_FILE = '{{BUDGET_FILE}}');

INSERT OVERWRITE INTO DIM_ENVIRONMENT
SELECT DENSE_RANK() OVER (ORDER BY ENVIRONMENT), ENVIRONMENT, ENVIRONMENT = 'production' FROM
  (SELECT DISTINCT ENVIRONMENT FROM CLOUDSPEND_AI.RAW.CLOUD_BILLING_RAW WHERE SOURCE_FILE = '{{SOURCE_FILE}}');

INSERT OVERWRITE INTO DIM_REGION
SELECT DENSE_RANK() OVER (ORDER BY REGION), REGION FROM
  (SELECT DISTINCT REGION FROM CLOUDSPEND_AI.RAW.CLOUD_BILLING_RAW WHERE SOURCE_FILE = '{{SOURCE_FILE}}');

-- Calendar covers whole months from the first to the last month present in billing or budgets.
INSERT OVERWRITE INTO DIM_DATE
WITH bounds AS (
  SELECT DATE_TRUNC('month', LEAST(MIN(USAGE_DATE),
           (SELECT MIN(BUDGET_MONTH) FROM CLOUDSPEND_AI.RAW.BUDGETS_RAW WHERE SOURCE_FILE = '{{BUDGET_FILE}}'))) AS d0,
         LAST_DAY(GREATEST(MAX(USAGE_DATE),
           (SELECT MAX(BUDGET_MONTH) FROM CLOUDSPEND_AI.RAW.BUDGETS_RAW WHERE SOURCE_FILE = '{{BUDGET_FILE}}'))) AS d1
  FROM CLOUDSPEND_AI.RAW.CLOUD_BILLING_RAW WHERE SOURCE_FILE = '{{SOURCE_FILE}}'
), days AS (
  SELECT DATEADD(day, ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1, b.d0) AS d, b.d1
  FROM bounds b, TABLE(GENERATOR(ROWCOUNT => 5000))
)
SELECT TO_NUMBER(TO_CHAR(d, 'YYYYMMDD')), d, YEAR(d), QUARTER(d), MONTH(d),
       TO_CHAR(d, 'YYYY-MM'), YEAR(d) || '-Q' || QUARTER(d),
       DATE_TRUNC('month', d), DATE_TRUNC('quarter', d),
       DAYOFWEEKISO(d), DAYNAME(d), DAYOFWEEKISO(d) >= 6
FROM days WHERE d <= d1;

INSERT OVERWRITE INTO FACT_CLOUD_COST
SELECT r.RECORD_ID, TO_NUMBER(TO_CHAR(r.USAGE_DATE, 'YYYYMMDD')), dep.DEPARTMENT_KEY, s.SERVICE_KEY,
       e.ENVIRONMENT_KEY, g.REGION_KEY, r.RESOURCE_ID, r.USAGE_UNITS, r.UNIT_COST, r.TOTAL_COST,
       r.SOURCE_FILE, CURRENT_TIMESTAMP()
FROM CLOUDSPEND_AI.RAW.CLOUD_BILLING_RAW r
JOIN DIM_DEPARTMENT dep ON dep.DEPARTMENT_NAME = r.DEPARTMENT
JOIN DIM_SERVICE s ON s.SERVICE_NAME = r.SERVICE_NAME
JOIN DIM_ENVIRONMENT e ON e.ENVIRONMENT_NAME = r.ENVIRONMENT
JOIN DIM_REGION g ON g.REGION_NAME = r.REGION
WHERE r.SOURCE_FILE = '{{SOURCE_FILE}}';

INSERT OVERWRITE INTO FACT_BUDGET
SELECT b.BUDGET_MONTH, dep.DEPARTMENT_KEY, s.SERVICE_KEY, b.BUDGET_AMOUNT, b.SOURCE_FILE, CURRENT_TIMESTAMP()
FROM CLOUDSPEND_AI.RAW.BUDGETS_RAW b
JOIN DIM_DEPARTMENT dep ON dep.DEPARTMENT_NAME = b.DEPARTMENT
JOIN DIM_SERVICE s ON s.SERVICE_NAME = b.SERVICE_NAME
WHERE b.SOURCE_FILE = '{{BUDGET_FILE}}';

INSERT OVERWRITE INTO ANOMALY_GROUND_TRUTH
SELECT RECORD_ID, IS_INJECTED_ANOMALY, ANOMALY_TYPE
FROM CLOUDSPEND_AI.RAW.CLOUD_BILLING_RAW WHERE SOURCE_FILE = '{{SOURCE_FILE}}';
