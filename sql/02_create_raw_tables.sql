-- RAW layer: source records as loaded. Logical PK noted in comments (Snowflake does not enforce).
USE WAREHOUSE CLOUDSPEND_WH;
USE SCHEMA CLOUDSPEND_AI.RAW;

-- Grain: one row per resource per day. Logical PK: RECORD_ID.
CREATE TABLE IF NOT EXISTS CLOUD_BILLING_RAW (
  RECORD_ID            VARCHAR NOT NULL,
  USAGE_DATE           DATE NOT NULL,
  DEPARTMENT           VARCHAR NOT NULL,
  SERVICE_NAME         VARCHAR NOT NULL,
  ENVIRONMENT          VARCHAR NOT NULL,
  REGION               VARCHAR NOT NULL,
  RESOURCE_ID          VARCHAR NOT NULL,
  USAGE_UNITS          NUMBER(18,2) NOT NULL,
  UNIT_COST            NUMBER(18,6) NOT NULL,
  TOTAL_COST           NUMBER(18,2) NOT NULL,
  IS_INJECTED_ANOMALY  BOOLEAN,          -- ground truth, evaluation only
  ANOMALY_TYPE         VARCHAR,
  GENERATED_AT         TIMESTAMP_NTZ,
  SOURCE_FILE          VARCHAR,
  LOADED_AT            TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Grain: source file x month x department x service. Logical PK: (SOURCE_FILE, BUDGET_MONTH, DEPARTMENT, SERVICE_NAME).
CREATE TABLE IF NOT EXISTS BUDGETS_RAW (
  BUDGET_MONTH   DATE NOT NULL,
  DEPARTMENT     VARCHAR NOT NULL,
  SERVICE_NAME   VARCHAR NOT NULL,
  BUDGET_AMOUNT  NUMBER(18,2) NOT NULL,
  SOURCE_FILE    VARCHAR,
  LOADED_AT      TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- One row per load attempt. Logical PK: RUN_ID.
CREATE TABLE IF NOT EXISTS INGESTION_RUNS (
  RUN_ID          VARCHAR NOT NULL,
  FILE_NAME       VARCHAR,
  STATUS          VARCHAR,       -- RUNNING | SUCCESS | FAILED
  ROWS_IN_FILE    NUMBER,
  ROWS_LOADED     NUMBER,
  SOURCE_COST_SUM NUMBER(18,2),
  LOADED_COST_SUM NUMBER(18,2),
  ERROR_SUMMARY   VARCHAR,
  STARTED_AT      TIMESTAMP_NTZ,
  FINISHED_AT     TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS DATA_QUALITY_ISSUES (
  RUN_ID      VARCHAR,
  SEVERITY    VARCHAR,           -- ERROR | WARNING
  MESSAGE     VARCHAR,
  CREATED_AT  TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE STAGE IF NOT EXISTS INGEST_STAGE;
