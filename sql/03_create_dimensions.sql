-- ANALYTICS dimensions. Surrogate keys are DENSE_RANK over the natural name and are rebuilt with the facts
-- in sql/05, so they are consistent within a build but NOT stable across builds if new members appear.
USE SCHEMA CLOUDSPEND_AI.ANALYTICS;

CREATE TABLE IF NOT EXISTS DIM_DATE (          -- PK DATE_KEY (yyyymmdd). Grain: one row per calendar day.
  DATE_KEY NUMBER(8) NOT NULL, FULL_DATE DATE NOT NULL, YEAR NUMBER(4), QUARTER NUMBER(1),
  MONTH NUMBER(2), YEAR_MONTH VARCHAR, YEAR_QUARTER VARCHAR, MONTH_START_DATE DATE, QUARTER_START_DATE DATE,
  DAY_OF_WEEK NUMBER(1), DAY_NAME VARCHAR, IS_WEEKEND BOOLEAN
);
CREATE TABLE IF NOT EXISTS DIM_DEPARTMENT  (DEPARTMENT_KEY NUMBER NOT NULL, DEPARTMENT_NAME VARCHAR NOT NULL);
CREATE TABLE IF NOT EXISTS DIM_SERVICE     (SERVICE_KEY NUMBER NOT NULL, SERVICE_NAME VARCHAR NOT NULL);
CREATE TABLE IF NOT EXISTS DIM_ENVIRONMENT (ENVIRONMENT_KEY NUMBER NOT NULL, ENVIRONMENT_NAME VARCHAR NOT NULL,
                                            IS_PRODUCTION BOOLEAN);
CREATE TABLE IF NOT EXISTS DIM_REGION      (REGION_KEY NUMBER NOT NULL, REGION_NAME VARCHAR NOT NULL);
