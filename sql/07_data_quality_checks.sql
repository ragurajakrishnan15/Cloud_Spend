-- Reconciliation / quality checks. ONE statement returning CHECK_NAME, EXPECTED, ACTUAL, PASSED (tolerance $0.01).
-- Placeholders are substituted by the Python runner. Expected = RAW or an independent derivation; actual = modeled layer.
WITH c AS (
  SELECT 'fact_row_count_equals_raw' AS CHECK_NAME,
    (SELECT COUNT(*) FROM CLOUDSPEND_AI.RAW.CLOUD_BILLING_RAW WHERE SOURCE_FILE = '{{SOURCE_FILE}}') AS EXPECTED,
    (SELECT COUNT(*) FROM CLOUDSPEND_AI.ANALYTICS.FACT_CLOUD_COST) AS ACTUAL
  UNION ALL SELECT 'fact_cost_equals_raw_cost',
    (SELECT SUM(TOTAL_COST) FROM CLOUDSPEND_AI.RAW.CLOUD_BILLING_RAW WHERE SOURCE_FILE = '{{SOURCE_FILE}}'),
    (SELECT SUM(TOTAL_COST) FROM CLOUDSPEND_AI.ANALYTICS.FACT_CLOUD_COST)
  UNION ALL SELECT 'fact_record_id_unique',
    (SELECT COUNT(*) FROM CLOUDSPEND_AI.ANALYTICS.FACT_CLOUD_COST),
    (SELECT COUNT(DISTINCT RECORD_ID) FROM CLOUDSPEND_AI.ANALYTICS.FACT_CLOUD_COST)
  UNION ALL SELECT 'fact_has_no_orphan_dimension_keys', 0,
    (SELECT COUNT(*) FROM CLOUDSPEND_AI.ANALYTICS.FACT_CLOUD_COST f
      WHERE NOT EXISTS (SELECT 1 FROM CLOUDSPEND_AI.ANALYTICS.DIM_DATE x WHERE x.DATE_KEY = f.DATE_KEY)
         OR NOT EXISTS (SELECT 1 FROM CLOUDSPEND_AI.ANALYTICS.DIM_DEPARTMENT x WHERE x.DEPARTMENT_KEY = f.DEPARTMENT_KEY)
         OR NOT EXISTS (SELECT 1 FROM CLOUDSPEND_AI.ANALYTICS.DIM_SERVICE x WHERE x.SERVICE_KEY = f.SERVICE_KEY)
         OR NOT EXISTS (SELECT 1 FROM CLOUDSPEND_AI.ANALYTICS.DIM_ENVIRONMENT x WHERE x.ENVIRONMENT_KEY = f.ENVIRONMENT_KEY)
         OR NOT EXISTS (SELECT 1 FROM CLOUDSPEND_AI.ANALYTICS.DIM_REGION x WHERE x.REGION_KEY = f.REGION_KEY))
  UNION ALL SELECT 'fact_has_no_negative_cost', 0,
    (SELECT COUNT(*) FROM CLOUDSPEND_AI.ANALYTICS.FACT_CLOUD_COST WHERE TOTAL_COST < 0)
  UNION ALL SELECT 'budget_row_count_equals_raw',
    (SELECT COUNT(*) FROM CLOUDSPEND_AI.RAW.BUDGETS_RAW WHERE SOURCE_FILE = '{{BUDGET_FILE}}'),
    (SELECT COUNT(*) FROM CLOUDSPEND_AI.ANALYTICS.FACT_BUDGET)
  UNION ALL SELECT 'budget_amount_equals_raw',
    (SELECT SUM(BUDGET_AMOUNT) FROM CLOUDSPEND_AI.RAW.BUDGETS_RAW WHERE SOURCE_FILE = '{{BUDGET_FILE}}'),
    (SELECT SUM(BUDGET_AMOUNT) FROM CLOUDSPEND_AI.ANALYTICS.FACT_BUDGET)
  UNION ALL SELECT 'budget_grain_unique',
    (SELECT COUNT(*) FROM CLOUDSPEND_AI.ANALYTICS.FACT_BUDGET),
    (SELECT COUNT(DISTINCT BUDGET_MONTH || '|' || DEPARTMENT_KEY || '|' || SERVICE_KEY)
       FROM CLOUDSPEND_AI.ANALYTICS.FACT_BUDGET)
  UNION ALL SELECT 'ground_truth_row_count_equals_fact',
    (SELECT COUNT(*) FROM CLOUDSPEND_AI.ANALYTICS.FACT_CLOUD_COST),
    (SELECT COUNT(*) FROM CLOUDSPEND_AI.ANALYTICS.ANOMALY_GROUND_TRUTH)
  UNION ALL SELECT 'view_daily_cost_equals_fact',
    (SELECT SUM(TOTAL_COST) FROM CLOUDSPEND_AI.ANALYTICS.FACT_CLOUD_COST),
    (SELECT SUM(TOTAL_COST) FROM CLOUDSPEND_AI.REPORTING.VW_DAILY_CLOUD_SPEND)
  UNION ALL SELECT 'view_monthly_cost_equals_fact',
    (SELECT SUM(TOTAL_COST) FROM CLOUDSPEND_AI.ANALYTICS.FACT_CLOUD_COST),
    (SELECT SUM(TOTAL_COST) FROM CLOUDSPEND_AI.REPORTING.VW_MONTHLY_CLOUD_SPEND)
  UNION ALL SELECT 'view_dept_trend_cost_equals_fact',
    (SELECT SUM(TOTAL_COST) FROM CLOUDSPEND_AI.ANALYTICS.FACT_CLOUD_COST),
    (SELECT SUM(TOTAL_COST) FROM CLOUDSPEND_AI.REPORTING.VW_DEPARTMENT_COST_TRENDS)
  UNION ALL SELECT 'view_service_trend_cost_equals_fact',
    (SELECT SUM(TOTAL_COST) FROM CLOUDSPEND_AI.ANALYTICS.FACT_CLOUD_COST),
    (SELECT SUM(TOTAL_COST) FROM CLOUDSPEND_AI.REPORTING.VW_SERVICE_COST_TRENDS)
  UNION ALL SELECT 'view_budget_variance_actual_equals_fact',
    (SELECT SUM(TOTAL_COST) FROM CLOUDSPEND_AI.ANALYTICS.FACT_CLOUD_COST),
    (SELECT SUM(ACTUAL_COST) FROM CLOUDSPEND_AI.REPORTING.VW_BUDGET_VARIANCE)
  UNION ALL SELECT 'view_budget_variance_budget_equals_fact',
    (SELECT SUM(BUDGET_AMOUNT) FROM CLOUDSPEND_AI.ANALYTICS.FACT_BUDGET),
    (SELECT SUM(BUDGET_AMOUNT) FROM CLOUDSPEND_AI.REPORTING.VW_BUDGET_VARIANCE)
  UNION ALL SELECT 'view_qbr_actual_equals_fact',
    (SELECT SUM(TOTAL_COST) FROM CLOUDSPEND_AI.ANALYTICS.FACT_CLOUD_COST),
    (SELECT SUM(ACTUAL_COST) FROM CLOUDSPEND_AI.REPORTING.VW_QBR_METRICS)
  UNION ALL SELECT 'view_qbr_budget_equals_fact',
    (SELECT SUM(BUDGET_AMOUNT) FROM CLOUDSPEND_AI.ANALYTICS.FACT_BUDGET),
    (SELECT SUM(BUDGET_AMOUNT) FROM CLOUDSPEND_AI.REPORTING.VW_QBR_METRICS)
)
SELECT CHECK_NAME, EXPECTED, ACTUAL, (ABS(COALESCE(EXPECTED, 0) - COALESCE(ACTUAL, 0)) <= 0.01) AS PASSED
FROM c ORDER BY CHECK_NAME
