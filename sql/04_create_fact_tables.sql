USE SCHEMA CLOUDSPEND_AI.ANALYTICS;

-- Grain: one row per source billing record (one resource-day). PK RECORD_ID -> RAW.CLOUD_BILLING_RAW.RECORD_ID.
-- FKs (logical): DATE_KEY, DEPARTMENT_KEY, SERVICE_KEY, ENVIRONMENT_KEY, REGION_KEY.
CREATE TABLE IF NOT EXISTS FACT_CLOUD_COST (
  RECORD_ID VARCHAR NOT NULL, DATE_KEY NUMBER(8) NOT NULL, DEPARTMENT_KEY NUMBER NOT NULL,
  SERVICE_KEY NUMBER NOT NULL, ENVIRONMENT_KEY NUMBER NOT NULL, REGION_KEY NUMBER NOT NULL,
  RESOURCE_ID VARCHAR NOT NULL, USAGE_UNITS NUMBER(18,2), UNIT_COST NUMBER(18,6), TOTAL_COST NUMBER(18,2) NOT NULL,
  SOURCE_FILE VARCHAR, CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Grain: month x department x service. Kept separate from daily facts so budgets are never double-counted.
CREATE TABLE IF NOT EXISTS FACT_BUDGET (
  BUDGET_MONTH DATE NOT NULL, DEPARTMENT_KEY NUMBER NOT NULL, SERVICE_KEY NUMBER NOT NULL,
  BUDGET_AMOUNT NUMBER(18,2) NOT NULL, SOURCE_FILE VARCHAR, CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Ground-truth labels for OFFLINE EVALUATION ONLY. Deliberately not on the fact table so they cannot leak into features.
CREATE TABLE IF NOT EXISTS ANOMALY_GROUND_TRUTH (
  RECORD_ID VARCHAR NOT NULL, IS_INJECTED_ANOMALY BOOLEAN, ANOMALY_TYPE VARCHAR
);

-- Model outputs (populated in Phase 5; schemas may be refined then).
-- Grain: one row per flagged record per detection method.
CREATE TABLE IF NOT EXISTS FACT_COST_ANOMALY (
  RECORD_ID VARCHAR NOT NULL, DETECTION_METHOD VARCHAR NOT NULL, METHOD_VERSION VARCHAR,
  OBSERVED_COST NUMBER(18,2), BASELINE_COST NUMBER(18,2), ABS_DIFF NUMBER(18,2), PCT_DIFF FLOAT,
  ANOMALY_SCORE FLOAT, SEVERITY VARCHAR, REASON VARCHAR, CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
-- Grain: one row per model x scope x forecast date.
CREATE TABLE IF NOT EXISTS FACT_COST_FORECAST (
  MODEL_NAME VARCHAR NOT NULL, MODEL_VERSION VARCHAR, SCOPE_TYPE VARCHAR, SCOPE_VALUE VARCHAR,
  FORECAST_DATE DATE NOT NULL, FORECAST_COST NUMBER(18,2), LOWER_BOUND NUMBER(18,2), UPPER_BOUND NUMBER(18,2),
  TRAINED_THROUGH_DATE DATE, CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
-- Grain: one row per recommendation. PK RECOMMENDATION_ID.
CREATE TABLE IF NOT EXISTS FACT_OPTIMIZATION_RECOMMENDATION (
  RECOMMENDATION_ID VARCHAR NOT NULL, RULE_NAME VARCHAR, RULE_VERSION VARCHAR,
  DEPARTMENT_KEY NUMBER, SERVICE_KEY NUMBER, PERIOD_START DATE, PERIOD_END DATE,
  EVIDENCE VARCHAR, SUGGESTED_ACTION VARCHAR, ESTIMATED_SAVINGS NUMBER(18,2), SAVINGS_FORMULA VARCHAR,
  CONFIDENCE VARCHAR, REVIEW_STATUS VARCHAR DEFAULT 'NEW', CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Evaluation metrics and parameters for every model run. Grain: run x model x scope x metric.
CREATE TABLE IF NOT EXISTS MODEL_EVALUATION (
  RUN_ID VARCHAR NOT NULL, MODEL_FAMILY VARCHAR NOT NULL, MODEL_NAME VARCHAR NOT NULL, MODEL_VERSION VARCHAR,
  SCOPE VARCHAR NOT NULL, METRIC_NAME VARCHAR NOT NULL, METRIC_VALUE FLOAT, PARAMETERS VARCHAR,
  CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
