-- ONE-TIME, run manually in a Snowsight worksheet as ACCOUNTADMIN. Not run by the pipeline.
-- Replace <PUBLIC_KEY> with the single-line public key body (no BEGIN/END lines).
USE ROLE ACCOUNTADMIN;
CREATE ROLE IF NOT EXISTS CLOUDSPEND_ROLE;
CREATE WAREHOUSE IF NOT EXISTS CLOUDSPEND_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
GRANT USAGE, OPERATE ON WAREHOUSE CLOUDSPEND_WH TO ROLE CLOUDSPEND_ROLE;
GRANT CREATE DATABASE ON ACCOUNT TO ROLE CLOUDSPEND_ROLE;  -- pipeline creates and owns CLOUDSPEND_AI
CREATE USER IF NOT EXISTS CLOUDSPEND_SVC TYPE = SERVICE
  DEFAULT_ROLE = CLOUDSPEND_ROLE DEFAULT_WAREHOUSE = CLOUDSPEND_WH
  RSA_PUBLIC_KEY = '<PUBLIC_KEY>';
GRANT ROLE CLOUDSPEND_ROLE TO USER CLOUDSPEND_SVC;
