-- ONE-TIME, run manually as ACCOUNTADMIN. Read-only access to REPORTING views for the dashboard / AI analyst.
-- Replace <APP_PUBLIC_KEY> with the single-line public key body (use $$ quoting).
USE ROLE ACCOUNTADMIN;
CREATE ROLE IF NOT EXISTS CLOUDSPEND_READER;
GRANT USAGE ON WAREHOUSE CLOUDSPEND_WH TO ROLE CLOUDSPEND_READER;
GRANT USAGE ON DATABASE CLOUDSPEND_AI TO ROLE CLOUDSPEND_READER;
GRANT USAGE ON SCHEMA CLOUDSPEND_AI.REPORTING TO ROLE CLOUDSPEND_READER;
GRANT SELECT ON ALL VIEWS IN SCHEMA CLOUDSPEND_AI.REPORTING TO ROLE CLOUDSPEND_READER;
-- Views are CREATE OR REPLACEd by the pipeline, which drops grants; FUTURE grants re-apply them.
GRANT SELECT ON FUTURE VIEWS IN SCHEMA CLOUDSPEND_AI.REPORTING TO ROLE CLOUDSPEND_READER;
CREATE USER IF NOT EXISTS CLOUDSPEND_APP TYPE = SERVICE
  DEFAULT_ROLE = CLOUDSPEND_READER DEFAULT_WAREHOUSE = CLOUDSPEND_WH;
ALTER USER CLOUDSPEND_APP SET RSA_PUBLIC_KEY = $$<APP_PUBLIC_KEY>$$;
GRANT ROLE CLOUDSPEND_READER TO USER CLOUDSPEND_APP;
